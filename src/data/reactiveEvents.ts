export function evaluateReactiveCrisis(params: ReactiveCrisisCheckParams): GameEvent | null {
  for (const crisis of REACTIVE_CRISIS_EVENTS) {
    if (crisis.checkTrigger(params)) {
      return {
        ...crisis,
        month: params.month,
      };
    }
  }
  return null;
}
