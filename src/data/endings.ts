export function evaluateEnding(
  resources: GameResources,
  factions: GameFactions,
  diplomacy: GameDiplomacy
): Ending {
  // Check for specialized victory & narrative paths first:
  // 1. Economic miracle:
  if (resources.budget >= 55 && resources.industry >= 55 && factions.people >= 45 && factions.army >= 40) {
    return ENDINGS_DATABASE.economic_miracle;
  }

  // 2. Sovereign fortress:
  if (diplomacy.sovereignty >= 65 && resources.military >= 55 && Math.abs(diplomacy.geopolitics) <= 30) {
    return ENDINGS_DATABASE.fortress;
  }

  // 3. Democracy:
  if (factions.people >= 55 && factions.intellectuals >= 55 && diplomacy.sovereignty >= 35) {
    return ENDINGS_DATABASE.democracy;
  }

  // 4. Junta:
  if (factions.army >= 65 && (factions.intellectuals <= 40 || factions.people <= 45)) {
    return ENDINGS_DATABASE.junta;
  }

  // 5. Socialist:
  if (factions.people >= 65 && factions.oligarchs <= 35) {
    return ENDINGS_DATABASE.socialist;
  }

  // 6. Plutocracy:
  if (factions.oligarchs >= 65 && factions.people <= 45) {
    return ENDINGS_DATABASE.plutocracy;
  }

  // 7. Western Bastion:
  if (diplomacy.geopolitics <= -30) {
    return ENDINGS_DATABASE.western_bastion;
  }

  // 8. Empire Vassal:
  if (diplomacy.geopolitics >= 30) {
    return ENDINGS_DATABASE.empire_vassal;
  }

  // Fallback to democracy or fortress depending on sovereignty
  if (diplomacy.sovereignty >= 50) {
    return ENDINGS_DATABASE.democracy;
  }

  return ENDINGS_DATABASE.plutocracy;
}
